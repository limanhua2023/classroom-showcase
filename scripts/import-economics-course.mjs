import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const DEFAULT_SOURCE_ROOT = 'D:/Users/ACER/ECONOMICS';
const DEFAULT_HTML_FILE = 'index_v1.17.4.html';
const COURSE_SLUG = 'economics-fundamentals';
const TARGET_DIR = path.join(repoRoot, 'public', 'courses', COURSE_SLUG);
const SUPPLEMENT_DIR = path.join(repoRoot, 'data', 'course-teacher-assets');
const SUPPLEMENT_FILE = path.join(SUPPLEMENT_DIR, `${COURSE_SLUG}-supplement.json`);
const TARGET_HTML_FILE = path.join(TARGET_DIR, 'index.html');
const TARGET_CHAPTERS_FILE = path.join(TARGET_DIR, 'chapters-data.js');
const TARGET_STORY_FILE = path.join(TARGET_DIR, 'story-data.js');

const TEACHER_ONLY_KEYS = new Set([
  'teacherAnswer',
  'boardAnswer',
  'teacherQuestions'
]);

function parseArgs(argv = process.argv.slice(2)) {
  const config = {
    sourceRoot: DEFAULT_SOURCE_ROOT,
    htmlFile: DEFAULT_HTML_FILE
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const next = argv[i + 1];
    if (arg === '--source-root' && next) {
      config.sourceRoot = next;
      i += 1;
      continue;
    }
    if (arg === '--html' && next) {
      config.htmlFile = next;
      i += 1;
    }
  }

  return config;
}

function readUtf8(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function writeUtf8(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function copyUtf8File(sourcePath, targetPath) {
  writeUtf8(targetPath, readUtf8(sourcePath));
}

function ensureRuntimeInjection(html) {
  const runtimeBlock = [
    '  <script src="/js/api.js"></script>',
    '  <script src="/js/course-runtime.js"></script>',
    '  <script src="/js/economics-course-adapter.js"></script>'
  ].join('\n');

  if (html.includes('/js/economics-course-adapter.js')) {
    return html;
  }

  if (/<\/body>/i.test(html)) {
    return html.replace(/<\/body>/i, `${runtimeBlock}\n</body>`);
  }

  return `${html}\n${runtimeBlock}\n`;
}

function normalizeImportedHtml(html) {
  return html
    .replace("version: '1.17.3'", "version: '1.17.4'")
    .replace("window.EconCourseBridge = {\n  version: '1.17.3'", "window.EconCourseBridge = {\n  version: '1.17.4'")
    .replace("window.EconCourseApp = {\n  version: '1.17.3'", "window.EconCourseApp = {\n  version: '1.17.4'")
    .replace("state: {\n    version: '1.17.3'", "state: {\n    version: '1.17.4'")
    .replace('教师课堂驾驶舱 · v1.16', '教师课堂驾驶舱 · v1.17.4');
}

function hasMeaningfulData(value) {
  if (value == null) return false;
  if (Array.isArray(value)) return value.some(item => hasMeaningfulData(item));
  if (typeof value === 'object') return Object.keys(value).length > 0;
  return true;
}

function stripTeacherData(value) {
  if (Array.isArray(value)) {
    return value.map(item => stripTeacherData(item));
  }
  if (value && typeof value === 'object') {
    const result = {};
    for (const [key, child] of Object.entries(value)) {
      if (TEACHER_ONLY_KEYS.has(key)) continue;
      result[key] = stripTeacherData(child);
    }
    return result;
  }
  return value;
}

function extractTeacherData(value) {
  if (Array.isArray(value)) {
    const items = value.map(item => extractTeacherData(item));
    return items.some(item => hasMeaningfulData(item)) ? items : null;
  }
  if (value && typeof value === 'object') {
    const result = {};
    for (const [key, child] of Object.entries(value)) {
      if (TEACHER_ONLY_KEYS.has(key)) {
        result[key] = child;
        continue;
      }
      const nested = extractTeacherData(child);
      if (hasMeaningfulData(nested)) {
        result[key] = nested;
      }
    }
    return hasMeaningfulData(result) ? result : null;
  }
  return null;
}

function loadChapterDatabase(sourcePath) {
  const context = vm.createContext({
    C: {},
    window: {},
    console
  });
  vm.runInContext(readUtf8(sourcePath), context, { filename: sourcePath });
  return context.C;
}

function buildStudentChaptersSource(sourcePath) {
  const chapterDb = loadChapterDatabase(sourcePath);
  const studentDb = stripTeacherData(chapterDb);
  const supplement = extractTeacherData(chapterDb) || {};

  const generatedJs = [
    '// Generated by scripts/import-economics-course.mjs',
    '// Student-safe economics chapter database. Teacher-only answers are served via authenticated API.',
    `window.C = ${JSON.stringify(studentDb, null, 2)};`,
    ''
  ].join('\n');

  return { generatedJs, supplement };
}

function main() {
  const { sourceRoot, htmlFile } = parseArgs();
  const sourceHtmlPath = path.resolve(sourceRoot, htmlFile);
  const sourceStoryPath = path.resolve(sourceRoot, 'story-data.js');
  const sourceChaptersPath = path.resolve(sourceRoot, 'chapters-data.js');

  if (!fs.existsSync(sourceHtmlPath)) {
    throw new Error(`Economics HTML source not found: ${sourceHtmlPath}`);
  }
  if (!fs.existsSync(sourceStoryPath)) {
    throw new Error(`Economics story data not found: ${sourceStoryPath}`);
  }
  if (!fs.existsSync(sourceChaptersPath)) {
    throw new Error(`Economics chapters data not found: ${sourceChaptersPath}`);
  }

  fs.mkdirSync(TARGET_DIR, { recursive: true });
  fs.mkdirSync(SUPPLEMENT_DIR, { recursive: true });

  const importedHtml = ensureRuntimeInjection(normalizeImportedHtml(readUtf8(sourceHtmlPath)));
  writeUtf8(TARGET_HTML_FILE, importedHtml);
  copyUtf8File(sourceStoryPath, TARGET_STORY_FILE);

  const { generatedJs, supplement } = buildStudentChaptersSource(sourceChaptersPath);
  writeUtf8(TARGET_CHAPTERS_FILE, generatedJs);
  writeUtf8(SUPPLEMENT_FILE, `${JSON.stringify(supplement, null, 2)}\n`);

  const result = {
    ok: true,
    source_root: sourceRoot,
    html_file: htmlFile,
    target_html: path.relative(repoRoot, TARGET_HTML_FILE),
    target_story: path.relative(repoRoot, TARGET_STORY_FILE),
    target_chapters: path.relative(repoRoot, TARGET_CHAPTERS_FILE),
    teacher_supplement: path.relative(repoRoot, SUPPLEMENT_FILE)
  };

  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

main();
